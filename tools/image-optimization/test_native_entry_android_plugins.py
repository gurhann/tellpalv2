"""APK admission refuses references, malformed code and unbound provenance."""
from hashlib import sha256
from pathlib import Path
import time
import tempfile
import os
import unittest
from unittest.mock import patch

import native_entry_android_plugins as plugins
from native_entry_config import EntryError, frozen_json
import native_entry_driver as driver
import android_plugin_registration_integration as integration

GENERATED = (b'package io.flutter.plugins;\n// This file is generated by the Flutter tool\n'
    b'public final class GeneratedPluginRegistrant {\n'
    b'public static void registerWith(@NonNull FlutterEngine flutterEngine) {}\n}\n')


def smali(name, body=".method public constructor <init>()V\n .registers 1\n return-void\n.end method\n"):
    return (".class public " + plugins.descriptor(name) + "\n.super Ljava/lang/Object;\n" + body).encode()


def registrant(engine=plugins.ENGINE, registry=plugins.REGISTRY, plugin=plugins.PLUGIN, add="add"):
    body = ".method public static registerWith(" + plugins.descriptor(engine) + ")V\n .registers 3\n"
    for name in plugins.JNI_PLUGINS:
        target = plugins.descriptor(name)
        body += (" new-instance v1, " + target + "\n invoke-direct {v1}, " + target + "-><init>()V\n"
            " invoke-virtual {v0, v1}, " + plugins.descriptor(registry) + "->" + add +
            "(" + plugins.descriptor(plugin) + ")V\n")
    return smali(plugins.REGISTRANT, body + " return-void\n.end method\n")


class AndroidPluginTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="native-plugin-test-")
        self.addCleanup(temporary.cleanup)
        self.base = Path(temporary.name).resolve()
        os.chmod(self.base, 0o700)
        self.mobile = self.base / "mobile"
        self.output = self.base / "inspection"
        self.output.mkdir(mode=0o700)
        self.app = self.file("app.apk", b"synthetic APK bytes")
        for path in (self.mobile / plugins.SOURCE, self.output / "gradle/app" / plugins.COPIED):
            path.parent.mkdir(parents=True)
            path.write_bytes(GENERATED)
            path.chmod(0o600)
        (self.output / "android-plugin-generation.json").write_bytes(frozen_json({"status": "ok"}))
        (self.output / "android-plugin-generation.json").chmod(0o600)
        self.calls = []

    def file(self, name, raw):
        path = self.base / name
        path.write_bytes(raw)
        path.chmod(0o600)
        return path

    def command(self, argv, output, alias, **kwargs):
        self.calls.append(argv)
        raw = registrant() if argv[-2] == plugins.REGISTRANT else smali(argv[-2])
        (output / (alias + ".stderr")).write_bytes(b"valid JVM diagnostic\n")
        (output / (alias + ".stderr")).chmod(0o600)
        (output / (alias + ".json")).write_bytes(frozen_json({"status": "ok"}))
        (output / (alias + ".json")).chmod(0o600)
        return raw

    def inspect(self, command=None, hash_function=None):
        return plugins.inspect_android_plugins(self.mobile, self.app, self.output, "profile",
            time.monotonic() + 5, command or self.command, hash_function or driver.artifact_hash)

    def test_profile_definitions_registration_and_nonempty_stderr_bind_to_apk(self):
        evidence = self.inspect()
        self.assertEqual(evidence["artifactSha256"], sha256(self.app.read_bytes()).hexdigest())
        self.assertEqual(evidence["generatedSourceSha256"], evidence["compiledSourceSha256"])
        self.assertEqual(len(evidence["inspections"]), 3)
        self.assertTrue(all(call[1:3] == ["dex", "code"] for call in self.calls))

    def test_release_mapping_only_resolves_engine_signature_and_registration_names(self):
        mapping = (plugins.ENGINE + " -> a.b:\n" + plugins.PLUGIN + " -> c.d:\n" + plugins.REGISTRY +
            " -> e.f:\n    1:5:void add(" + plugins.PLUGIN + "):128:132 -> x\n").encode()
        classes, add = plugins.mapping_names(mapping)
        plugins.registration_code(registrant("a.b", "e.f", "c.d", "x"), classes, add)
        with self.assertRaisesRegex(EntryError, "android_plugin_definition_rejected"):
            plugins.registration_code(b"const-class v0, Lio/flutter/plugins/GeneratedPluginRegistrant;\n", classes, add)
        for raw in (b"", mapping + mapping, mapping.replace(b" -> x", b" -> bad-name"), b"\xff"):
            with self.subTest(raw=raw), self.assertRaisesRegex(EntryError, "android_plugin_mapping_rejected"):
                plugins.mapping_names(raw)

    def test_reference_only_decoys_wrong_class_empty_and_truncated_outputs_refuse(self):
        for raw in (b"", b"C r 0 1 0 io.flutter.plugins.GeneratedPluginRegistrant\n",
                smali("decoy.Class", "const-string v0, \"io.flutter.plugins.GeneratedPluginRegistrant\"\n"),
                registrant().replace(b".end method\n", b""), b"\xff"):
            with self.subTest(raw=raw), self.assertRaises(EntryError):
                plugins.registration_code(raw, {}, "add")

    def test_whitespace_only_class_and_method_headers_have_fixed_bounded_refusals(self):
        raw = registrant()
        class_header = b".class public " + plugins.descriptor(plugins.REGISTRANT).encode()
        for whitespace in (b" ", b"\t  "):
            with self.subTest(header="class", whitespace=whitespace), \
                    self.assertRaisesRegex(EntryError, "^android_plugin_definition_rejected$"):
                plugins.registration_code(raw.replace(class_header, b".class " + whitespace), {}, "add")
            broken = raw.replace(b".method public static registerWith(" + plugins.descriptor(plugins.ENGINE).encode() + b")V",
                b".method " + whitespace)
            with self.subTest(header="method", whitespace=whitespace), \
                    self.assertRaisesRegex(EntryError, "^android_registration_method_rejected$"):
                plugins.registration_code(broken, {}, "add")

    def test_reflection_requires_public_registrant_class(self):
        raw = registrant()
        for visibility in (b"", b"private ", b"protected "):
            with self.subTest(visibility=visibility), \
                    self.assertRaisesRegex(EntryError, "^android_plugin_definition_rejected$"):
                plugins.registration_code(raw.replace(b".class public ", b".class " + visibility), {}, "add")

    def test_non_callable_method_missing_jni_creation_or_registration_refuse(self):
        raw = registrant()
        for broken in (raw.replace(b"public static registerWith", b"private static registerWith"),
                raw.replace(b"public static registerWith", b"public native registerWith"),
                raw.replace(b"registerWith(", b"referenceOnly("), raw.replace(b"return-void", b"nop"),
                raw.replace(b"new-instance", b"const-string"), raw.replace(b"invoke-direct", b"invoke-static"),
                raw.replace(b"->add(", b"->referenceOnly("), raw.replace(b"{v0, v1}", b"{v0, v2}")):
            with self.subTest(broken=broken), self.assertRaises(EntryError):
                plugins.registration_code(broken, {}, "add")

    def test_missing_empty_incompatible_or_stale_generated_sources_refuse(self):
        target = self.mobile / plugins.SOURCE
        for raw in (b"", b"cached incompatible source"):
            target.write_bytes(raw)
            with self.assertRaisesRegex(EntryError, "android_registrant_source_rejected"):
                self.inspect()
        target.write_bytes(GENERATED + b"// changed\n")
        with self.assertRaisesRegex(EntryError, "android_registrant_copy_rejected"):
            self.inspect()
        target.unlink()
        with self.assertRaises(EntryError):
            self.inspect()
        self.assertEqual(self.calls, [])

    def test_tool_timeout_failure_and_apk_mutation_never_admit(self):
        for reason in ("tool_timeout", "tool_failed", "tool_output_limit"):
            with self.subTest(reason=reason), self.assertRaisesRegex(EntryError, reason):
                self.inspect(command=lambda *args, **kwargs: (_ for _ in ()).throw(EntryError(reason)))
        hashes = iter(("a" * 64, "b" * 64))
        with self.assertRaisesRegex(EntryError, "android_plugin_binding_changed"):
            self.inspect(hash_function=lambda _: next(hashes))

    def test_sdk_mode_generator_uses_existing_sdk_without_pub_or_manual_plugin_list(self):
        sdk = self.base / "sdk"
        source = sdk / "packages/flutter_tools/lib/src/flutter_plugins.dart"
        config = sdk / "packages/flutter_tools/.dart_tool/package_config.json"
        for path in (source, config):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(b"synthetic SDK input")
            path.chmod(0o644)
        for mode in ("profile", "release"):
            output = self.output / mode
            output.mkdir(mode=0o700)
            def command(argv, target, alias, **kwargs):
                self.assertEqual(argv, [str(sdk / "bin/cache/dart-sdk/bin/dart"), "--packages=" + str(config),
                    str(output / "android-sdk-registrant.dart"), str(sdk), str(self.mobile), mode])
                self.assertEqual(alias, "android-plugin-generation")
                self.assertEqual((output / "android-sdk-registrant.dart").read_bytes(), plugins.SDK_GENERATOR)
                return b"ANDROID_SDK_REGISTRANT_GENERATED\n"
            with patch.object(plugins.shutil, "which", return_value=str(sdk / "bin/flutter")):
                evidence = plugins.generate_android_registrant(self.mobile, output, mode, time.monotonic() + 5, command)
            self.assertEqual(evidence["sdkGeneratorSha256"], sha256(source.read_bytes()).hexdigest())
            self.assertEqual(source.stat().st_mode & 0o777, 0o644)

    def test_sdk_generator_failure_and_sdk_mutation_refuse(self):
        sdk = self.base / "sdk"
        source = sdk / "packages/flutter_tools/lib/src/flutter_plugins.dart"
        config = sdk / "packages/flutter_tools/.dart_tool/package_config.json"
        for path in (source, config):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(b"synthetic SDK input")
        for index, result in enumerate((b"", b"ANDROID_SDK_REGISTRANT_GENERATED\nextra\n", None)):
            output = self.output / str(index)
            output.mkdir(mode=0o700)
            def command(*args, **kwargs):
                if result is None:
                    source.write_bytes(b"changed SDK generator")
                    return b"ANDROID_SDK_REGISTRANT_GENERATED\n"
                return result
            with patch.object(plugins.shutil, "which", return_value=str(sdk / "bin/flutter")), \
                    self.assertRaisesRegex(EntryError, "android_plugin_generation_rejected"):
                plugins.generate_android_registrant(self.mobile, output, "release", time.monotonic() + 5, command)


    def test_sdk_mode_content_check_catches_release_mode_false_output(self):
        statements = b"\n".join(("flutterEngine.getPlugins().add(new " + name + "());").encode()
            for name in plugins.JNI_PLUGINS)
        dev = ("flutterEngine.getPlugins().add(new " + integration.DEV_PLUGIN + "());").encode()
        self.assertTrue(integration.check_plugin_content(statements + dev, "profile")["integrationTestPresent"])
        self.assertFalse(integration.check_plugin_content(statements, "release")["integrationTestPresent"])
        for raw, mode in ((statements + dev, "release"), (statements, "profile"), (dev, "profile")):
            with self.subTest(mode=mode, raw=raw), \
                    self.assertRaisesRegex(EntryError, "^integration_sdk_mode_mismatch$"):
                integration.check_plugin_content(raw, mode)

    def test_explicit_integration_absent_or_incomplete_inputs_refuse_without_skips(self):
        with self.assertRaises(EntryError):
            integration.load_inputs(self.base / "absent-config.json")
        configuration = self.file("incomplete-integration.json", frozen_json({"scope": integration.SCOPE, "schemaVersion": 1}))
        with self.assertRaisesRegex(EntryError, "^schema_rejected$"):
            integration.load_inputs(configuration)
