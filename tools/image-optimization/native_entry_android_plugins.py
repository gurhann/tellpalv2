"""Bound APK admission to raw DEX definitions and SDK-generated registration."""
from hashlib import sha256
from pathlib import Path
import os
import re
import shutil
import stat

from native_entry_config import open_nofollow, private_file, require

REGISTRANT = "io.flutter.plugins.GeneratedPluginRegistrant"
ENGINE = "io.flutter.embedding.engine.FlutterEngine"
PLUGIN = "io.flutter.embedding.engine.plugins.FlutterPlugin"
REGISTRY = "io.flutter.embedding.engine.FlutterEngineConnectionRegistry"
PLUGIN_REGISTRY = "io.flutter.embedding.engine.plugins.PluginRegistry"
JNI_PLUGINS = ("com.github.dart_lang.jni.JniPlugin", "com.github.dart_lang.jni_flutter.JniFlutterPlugin")
SOURCE = Path("android/app/src/main/java/io/flutter/plugins/GeneratedPluginRegistrant.java")
COPIED = Path("generated/imageExperimentRegistrant/io/flutter/plugins/GeneratedPluginRegistrant.java")
NAME = r"[A-Za-z_$][A-Za-z0-9_.$]*"
SDK_GENERATOR = b"""import 'package:flutter_tools/src/cache.dart';
import 'package:flutter_tools/src/base/template.dart';
import 'package:flutter_tools/src/context_runner.dart';
import 'package:flutter_tools/src/flutter_plugins.dart';
import 'package:flutter_tools/src/globals.dart' as globals;
import 'package:flutter_tools/src/isolated/mustache_template.dart';
import 'package:flutter_tools/src/project.dart';
Future<void> main(List<String> args) async {
  Cache.flutterRoot = args[0];
  await runInContext(() async {
    final project = FlutterProject.fromDirectory(globals.fs.directory(args[1]));
    await injectPlugins(project, releaseMode: args[2] == 'release', androidPlatform: true);
  }, overrides: {TemplateRenderer: () => const MustacheTemplateRenderer()});
  print('ANDROID_SDK_REGISTRANT_GENERATED');
}
"""


def generate_android_registrant(mobile, output, mode, deadline, checked_run):
    """Call the selected SDK generator without another Pub resolution or SDK edits."""
    require(mode in ("profile", "release"), "android_plugin_mode_rejected")
    selected = shutil.which("flutter")
    require(selected is not None, "native_tool_unavailable")
    sdk = Path(selected).resolve().parent.parent
    package_config = sdk / "packages/flutter_tools/.dart_tool/package_config.json"
    generator = sdk / "packages/flutter_tools/lib/src/flutter_plugins.dart"
    before = sha256(sdk_file(generator, 256 * 1024)).hexdigest()
    package_hash = sha256(sdk_file(package_config, 1024 * 1024)).hexdigest()
    wrapper = Path(output) / "android-sdk-registrant.dart"
    with os.fdopen(open_nofollow(wrapper, os.O_WRONLY | os.O_CREAT | os.O_EXCL), "wb") as handle:
        handle.write(SDK_GENERATOR)
    result = checked_run([str(sdk / "bin/cache/dart-sdk/bin/dart"), "--packages=" + str(package_config),
        str(wrapper), str(sdk), str(mobile), mode], output, "android-plugin-generation",
        deadline=deadline, cwd=mobile)
    require(result == b"ANDROID_SDK_REGISTRANT_GENERATED\n" and
        sha256(sdk_file(generator, 256 * 1024)).hexdigest() == before and
        sha256(sdk_file(package_config, 1024 * 1024)).hexdigest() == package_hash,
        "android_plugin_generation_rejected")
    return {"sdkGeneratorSha256": before, "sdkPackageConfigSha256": package_hash,
        "sdkInvocationSha256": sha256(SDK_GENERATOR).hexdigest()}


def sdk_file(path, limit):
    """SDK sources are public inputs; keep their original permissions and bytes."""
    with os.fdopen(open_nofollow(path, os.O_RDONLY | os.O_NONBLOCK), "rb") as handle:
        before = os.fstat(handle.fileno())
        require(stat.S_ISREG(before.st_mode) and before.st_size <= limit, "android_plugin_sdk_rejected")
        raw = handle.read(limit + 1)
        after = os.fstat(handle.fileno())
        require(len(raw) == before.st_size and before == after and
            before.st_mtime_ns == after.st_mtime_ns and before.st_ctime_ns == after.st_ctime_ns and
            after == os.lstat(path), "android_plugin_sdk_rejected")
        return raw


def descriptor(name):
    return "L" + name.replace(".", "/") + ";"


def generated_source(path):
    raw = private_file(path, 65536, exact_mode=False)
    require(raw and b"This file is generated by the Flutter tool" in raw and
        b"package io.flutter.plugins;" in raw and b"public final class GeneratedPluginRegistrant" in raw and
        b"public static void registerWith(@NonNull FlutterEngine flutterEngine)" in raw,
        "android_registrant_source_rejected")
    return sha256(raw).hexdigest()


def mapping_names(raw):
    """Mapping resolves names only; it never establishes an APK definition."""
    try:
        text = raw.decode("utf-8")
    except UnicodeError:
        require(False, "android_plugin_mapping_rejected")
    classes, add, current = {}, set(), None
    for line in text.splitlines():
        match = re.fullmatch("(" + NAME + ") -> (" + NAME + "):", line)
        if match:
            current = match[1]
            require(current not in classes, "android_plugin_mapping_rejected")
            classes[current] = match[2]
        elif current == REGISTRY:
            method = re.fullmatch(r"\s+(?:\d+:\d+:)?void add\(" + re.escape(PLUGIN) +
                r"\)(?::\d+(?::\d+)?)? -> (" + NAME + ")", line)
            if method:
                add.add(method[1])
    require(all(name in classes for name in (ENGINE, PLUGIN, REGISTRY)) and len(add) == 1,
        "android_plugin_mapping_rejected")
    return classes, next(iter(add))


def defined_class(raw, name):
    try:
        text = raw.decode("utf-8")
    except UnicodeError:
        require(False, "android_plugin_definition_rejected")
    declarations = re.findall(r"^\.class ([^\n]+)$", text, re.M)
    tokens = declarations[0].split() if len(declarations) == 1 else []
    require(tokens and tokens[-1] == descriptor(name) and
        re.search(r"^\.super L[^\s;]+;$", text, re.M) and
        text.strip().endswith(".end method") and
        0 < len(re.findall(r"^\.method ", text, re.M)) == len(re.findall(r"^\.end method$", text, re.M)),
        "android_plugin_definition_rejected")
    return text


def registration_code(raw, classes, add):
    text = defined_class(raw, REGISTRANT)
    require("public" in re.search(r"^\.class ([^\n]+)$", text, re.M)[1].split(),
        "android_plugin_definition_rejected")
    signature = "registerWith(" + descriptor(classes.get(ENGINE, ENGINE)) + ")V"
    matches = re.findall(r"^\.method ([^\n]+)\n(.*?)^\.end method$", text, re.M | re.S)
    methods = [(header.split(), body) for header, body in matches]
    require(all(tokens for tokens, _ in methods), "android_registration_method_rejected")
    selected = [(tokens, body) for tokens, body in methods if tokens[-1] == signature]
    require(len(selected) == 1 and set(("public", "static")).issubset(selected[0][0]) and
        not set(("abstract", "native")).intersection(selected[0][0]), "android_registration_method_rejected")
    body = selected[0][1]
    require(re.search(r"^\s+return-void$", body, re.M), "android_registration_code_rejected")
    registry = "(?:" + "|".join(re.escape(descriptor(classes.get(name, name))) for name in
        (REGISTRY, PLUGIN_REGISTRY)) + ")"
    plugin = descriptor(classes.get(PLUGIN, PLUGIN))
    for name in JNI_PLUGINS:
        target = descriptor(name)
        created = re.search(r"^\s+new-instance ([vp]\d+), " + re.escape(target) + "$", body, re.M)
        require(created is not None, "android_registration_code_rejected")
        register = created[1]
        remainder = body[created.end():]
        constructor = re.search(r"^\s+invoke-direct \{" + register + r"\}, " +
            re.escape(target) + r"-><init>\(\)V$", remainder, re.M)
        require(constructor is not None, "android_registration_code_rejected")
        require(re.search(r"^\s+invoke-(?:virtual|interface) \{[vp]\d+, " + register + r"\}, " +
            registry + re.escape("->" + add + "(" + plugin + ")V") + "$",
            remainder[constructor.end():], re.M), "android_registration_code_rejected")


def inspect_android_plugins(mobile, app, output, mode, deadline, checked_run, artifact_hash):
    """Use bounded private tool traces, without rejecting valid diagnostic stderr."""
    mobile, output, app = Path(mobile), Path(output), Path(app)
    before = artifact_hash(app)
    source_hash = generated_source(mobile / SOURCE)
    copied_hash = generated_source(output / "gradle/app" / COPIED)
    require(source_hash == copied_hash, "android_registrant_copy_rejected")
    classes, add, mapping_hash = {}, "add", None
    if mode == "release":
        mapping = private_file(output / "gradle/app/outputs/mapping/release/mapping.txt",
            16 * 1024 * 1024, exact_mode=False)
        classes, add = mapping_names(mapping)
        mapping_hash = sha256(mapping).hexdigest()
    require(mode in ("profile", "release"), "android_plugin_mode_rejected")
    inspections = {}
    for index, name in enumerate((REGISTRANT, *JNI_PLUGINS)):
        alias = "android-plugin-" + str(index)
        raw = checked_run(["apkanalyzer", "dex", "code", "--class", name, str(app)],
            output, alias, deadline=deadline)
        defined_class(raw, name)
        if name == REGISTRANT:
            registration_code(raw, classes, add)
        inspections[name] = {"stdoutSha256": sha256(raw).hexdigest(),
            "stderrSha256": sha256(private_file(output / (alias + ".stderr"))).hexdigest(),
            "commandReceiptSha256": sha256(private_file(output / (alias + ".json"))).hexdigest()}
    require(artifact_hash(app) == before and generated_source(mobile / SOURCE) == source_hash and
        generated_source(output / "gradle/app" / COPIED) == copied_hash,
        "android_plugin_binding_changed")
    if mode == "release":
        require(sha256(private_file(output / "gradle/app/outputs/mapping/release/mapping.txt",
            16 * 1024 * 1024, exact_mode=False)).hexdigest() == mapping_hash, "android_plugin_binding_changed")
    return {"artifactSha256": before, "generatedSourceSha256": source_hash,
        "compiledSourceSha256": copied_hash, "mappingSha256": mapping_hash,
        "generationReceiptSha256": sha256(private_file(output / "android-plugin-generation.json")).hexdigest(),
        "inspections": inspections, "status": "defined_registration_verified"}
