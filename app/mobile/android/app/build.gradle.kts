val prepareExperimentRegistrant = if (experimentEnabled) tasks.register("prepareImageExperimentRegistrant") {
    // A plain task always validates missing input; a Copy task can silently become NO-SOURCE.
    outputs.upToDateWhen { false }
    doLast {
        val destination = experimentRegistrantDirectory.get().asFile
        delete(destination)
        val source = file("src/main/java/io/flutter/plugins/GeneratedPluginRegistrant.java").toPath()
        if (!Files.isRegularFile(source, LinkOption.NOFOLLOW_LINKS) || source.toRealPath() != source.toAbsolutePath() ||
            Files.size(source) !in 1..65536) throw GradleException("EXPERIMENT_REGISTRANT_REFUSED")
        val generated = try { Files.readString(source) } catch (_: Exception) {
            throw GradleException("EXPERIMENT_REGISTRANT_REFUSED")
        }
        if (!generated.contains("This file is generated by the Flutter tool") ||
            !generated.contains("package io.flutter.plugins;") ||
            !generated.contains("public final class GeneratedPluginRegistrant") ||
            !generated.contains("public static void registerWith(@NonNull FlutterEngine flutterEngine)")) {
            throw GradleException("EXPERIMENT_REGISTRANT_REFUSED")
        }
        val target = destination.resolve("io/flutter/plugins/GeneratedPluginRegistrant.java")
        target.parentFile.mkdirs()
        Files.copy(source, target.toPath())
    }
} else null
