-- Historical scalar provenance deliberately has no FK to editable content/page/asset rows.
create table reading_image_jobs (
    id uuid primary key,
    revision varchar(64) not null unique check (revision ~ '^[0-9a-f]{64}$'),
    work_json text not null,
    source_set varchar(64) not null,
    profile_set varchar(64) not null,
    status varchar(20) not null default 'PENDING' check (status in ('PENDING','PROCESSING','COMPLETED','FAILED')),
    attempt integer not null default 0 check (attempt >= 0),
    lease uuid,
    lease_expires_at timestamptz,
    manifest_digest varchar(64),
    diagnostic text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check ((status = 'COMPLETED') = (manifest_digest is not null)),
    check (status <> 'PROCESSING' or (attempt > 0 and lease is not null and lease_expires_at is not null))
);
create table reading_image_manifests (
    revision varchar(64) primary key references reading_image_jobs(revision),
    job_id uuid not null unique references reading_image_jobs(id),
    digest varchar(64) not null check (digest ~ '^[0-9a-f]{64}$'),
    manifest_json text not null,
    created_at timestamptz not null default now(),
    unique(revision,digest)
);
alter table reading_image_jobs add constraint fk_reading_job_manifest foreign key (revision,manifest_digest)
    references reading_image_manifests(revision,digest) deferrable initially deferred;
create table reading_image_attempt_evidence (
    id bigint generated by default as identity primary key,
    job_id uuid not null references reading_image_jobs(id),
    attempt integer not null,
    lease uuid not null,
    kind varchar(30) not null,
    detail text not null,
    created_at timestamptz not null default now()
);
-- Diagnostic deduplication only; media identities continue to use SHA-256.
create unique index reading_image_evidence_dedup on reading_image_attempt_evidence(job_id,attempt,lease,kind,md5(detail));
create table reading_image_integrity (
    id bigint generated by default as identity primary key,
    revision varchar(64) not null references reading_image_jobs(revision),
    checked_at timestamptz not null default now(),
    valid boolean not null,
    detail text not null
);
create index reading_image_integrity_revision on reading_image_integrity(revision,checked_at);
create index reading_image_pending on reading_image_jobs(status,lease_expires_at,created_at);
create function reading_image_immutable_manifest() returns trigger language plpgsql as $$
begin
    raise exception 'Reading manifests are immutable';
end;
$$;
create trigger reading_image_manifest_immutable before update or delete on reading_image_manifests
    for each row execute function reading_image_immutable_manifest();

create function reading_image_guard_job() returns trigger language plpgsql as $$
begin
    if new.revision <> old.revision or new.work_json <> old.work_json or new.source_set <> old.source_set or new.profile_set <> old.profile_set then
        raise exception 'Captured reading work is immutable';
    end if;
    if old.status = 'COMPLETED' and new is distinct from old then
        raise exception 'Completed reading jobs are immutable';
    end if;
    if old.status = 'FAILED' and new.status not in ('FAILED','PENDING') then
        raise exception 'Failed reading work requires explicit retry';
    end if;
    return new;
end;
$$;
create trigger reading_image_job_guard before update on reading_image_jobs for each row execute function reading_image_guard_job();

-- Planned source ownership is durable before external create, including interrupted pre-job capture.
create table reading_image_source_captures (
    capture_id uuid not null,
    object_path text not null,
    provider varchar(50) not null,
    sha256 varchar(64) not null,
    object_version text,
    job_id uuid references reading_image_jobs(id),
    created_at timestamptz not null default now(),
    primary key(capture_id,object_path)
);
create index reading_image_capture_job on reading_image_source_captures(job_id);
