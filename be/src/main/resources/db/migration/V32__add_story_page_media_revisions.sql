alter table asset_processing
    drop constraint chk_asset_processing_processing_kind,
    add constraint chk_asset_processing_processing_kind
        check (processing_kind in ('DELIVERY', 'STORY_NARRATION', 'STORY_PAGE_MEDIA')),
    add column page_source_snapshot text null,
    add column page_source_followup_snapshot text null;

create table story_page_media_manifests (
    id bigint generated by default as identity primary key,
    content_id bigint not null references contents (id),
    language_code varchar(8) not null,
    revision varchar(64) not null,
    profile_version varchar(80) not null,
    schema_version integer not null,
    created_at timestamptz not null default now(),
    constraint uk_story_page_media_manifest_revision unique (content_id, language_code, revision),
    constraint fk_story_page_media_manifest_localization
        foreign key (content_id, language_code)
        references content_localizations (content_id, language_code),
    constraint chk_story_page_media_manifest_revision check (revision ~ '^[0-9a-f]{64}$'),
    constraint chk_story_page_media_manifest_profile check (btrim(profile_version) <> ''),
    constraint chk_story_page_media_manifest_schema check (schema_version > 0)
);

alter table media_assets
    drop constraint chk_media_assets_kind,
    drop constraint chk_media_assets_kind_matches_media_type,
    add constraint chk_media_assets_kind check (
        kind in ('ORIGINAL_IMAGE', 'ORIGINAL_AUDIO', 'THUMBNAIL_PHONE', 'THUMBNAIL_TABLET',
                 'DETAIL_PHONE', 'DETAIL_TABLET', 'STORY_PAGE_RENDITION', 'OPTIMIZED_AUDIO',
                 'CONTENT_ZIP', 'CONTENT_ZIP_PART1', 'CONTENT_ZIP_PART2')
    ),
    add constraint chk_media_assets_kind_matches_media_type check (
        (media_type = 'IMAGE' and kind in ('ORIGINAL_IMAGE', 'THUMBNAIL_PHONE', 'THUMBNAIL_TABLET',
                                           'DETAIL_PHONE', 'DETAIL_TABLET', 'STORY_PAGE_RENDITION'))
        or (media_type = 'AUDIO' and kind in ('ORIGINAL_AUDIO', 'OPTIMIZED_AUDIO'))
        or (media_type = 'ARCHIVE' and kind in ('CONTENT_ZIP', 'CONTENT_ZIP_PART1', 'CONTENT_ZIP_PART2'))
    );

create table story_page_media_manifest_entries (
    id bigint generated by default as identity primary key,
    manifest_id bigint not null references story_page_media_manifests (id) on delete cascade,
    page_id bigint not null references story_pages (id),
    page_number integer not null,
    source_asset_id bigint not null references media_assets (id),
    rendition_asset_id bigint not null references media_assets (id),
    audio_asset_id bigint null references media_assets (id),
    source_checksum_sha256 varchar(64) not null,
    width integer not null,
    height integer not null,
    constraint uk_story_page_media_manifest_page unique (manifest_id, page_id),
    constraint uk_story_page_media_manifest_order unique (manifest_id, page_number),
    constraint chk_story_page_media_manifest_entry_order check (page_number > 0),
    constraint chk_story_page_media_manifest_entry_dimensions check (width > 0 and height > 0),
    constraint chk_story_page_media_manifest_source_checksum check (source_checksum_sha256 ~ '^[0-9a-f]{64}$')
);

create index idx_story_page_media_manifests_lookup
    on story_page_media_manifests (content_id, language_code, created_at desc);
