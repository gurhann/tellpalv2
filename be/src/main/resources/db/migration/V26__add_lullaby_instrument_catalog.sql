CREATE OR REPLACE FUNCTION ensure_lullaby_instrument_content_type() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM contents
         WHERE id = NEW.content_id
           AND type = 'LULLABY'
    ) THEN
        RAISE EXCEPTION 'Lullaby instrument requires LULLABY content: %', NEW.content_id
            USING errcode = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_lullaby_instruments_ensure_content_type
    BEFORE INSERT OR UPDATE OF content_id ON lullaby_instruments
    FOR EACH ROW
EXECUTE FUNCTION ensure_lullaby_instrument_content_type();

CREATE OR REPLACE FUNCTION ensure_lullaby_content_instrument_type_transition() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.type <> 'LULLABY' AND EXISTS (
        SELECT 1
          FROM lullaby_instruments
         WHERE content_id = NEW.id
    ) THEN
        RAISE EXCEPTION 'Content % cannot leave LULLABY while instruments exist', NEW.id
            USING errcode = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_contents_ensure_lullaby_instrument_type_transition
    BEFORE UPDATE OF type ON contents
    FOR EACH ROW
EXECUTE FUNCTION ensure_lullaby_content_instrument_type_transition();
