alter table asset_processing drop constraint chk_asset_processing_processing_kind,
    add constraint chk_asset_processing_processing_kind check (processing_kind in ('DELIVERY','STORY_NARRATION','STORY_PAGE_MEDIA','LISTING_COVER')),
    add column listing_profile_version varchar(180) null,
    add constraint chk_listing_cover_job_context check (processing_kind <> 'LISTING_COVER' or
        (target_scope='LOCALIZATION' and content_type='STORY' and cover_source_asset_id is not null and cover_source_asset_id > 0
         and listing_profile_version is not null and btrim(listing_profile_version) <> ''));

create table listing_cover_revisions (
    id bigint generated by default as identity primary key,
    content_id bigint not null,
    language_code varchar(8) not null,
    source_asset_id bigint not null references media_assets(id),
    source_checksum_sha256 varchar(64) not null check (source_checksum_sha256 ~ '^[0-9a-f]{64}$'),
    profile_version varchar(180) not null,
    revision varchar(64) not null check (revision ~ '^[0-9a-f]{64}$'),
    phone_asset_id bigint not null references media_assets(id),
    tablet_asset_id bigint not null references media_assets(id),
    phone_width integer not null check (phone_width > 0),
    phone_height integer not null check (phone_height > 0),
    tablet_width integer not null check (tablet_width > 0),
    tablet_height integer not null check (tablet_height > 0),
    created_at timestamptz not null default now(),
    constraint fk_listing_cover_localization foreign key (content_id,language_code) references content_localizations(content_id,language_code),
    constraint uk_listing_cover_revision unique(content_id,language_code,revision),
    constraint uk_listing_cover_source_profile unique(content_id,language_code,source_asset_id,profile_version),
    constraint chk_listing_cover_distinct_variants check (phone_asset_id <> tablet_asset_id)
);

create function ensure_listing_cover_verified_assets() returns trigger language plpgsql as $$
begin
    if not exists(select 1 from media_assets where id=new.phone_asset_id and media_type='IMAGE'
        and kind='THUMBNAIL_PHONE' and mime_type='image/jpeg' and byte_size>0 and checksum_sha256 ~ '^[0-9a-f]{64}$')
       or not exists(select 1 from media_assets where id=new.tablet_asset_id and media_type='IMAGE'
        and kind='THUMBNAIL_TABLET' and mime_type='image/jpeg' and byte_size>0 and checksum_sha256 ~ '^[0-9a-f]{64}$') then
        raise exception 'Listing covers require verified image registry metadata' using errcode='23514';
    end if;
    return new;
end;
$$;
create trigger trg_listing_cover_verified_assets before insert or update on listing_cover_revisions
    for each row execute function ensure_listing_cover_verified_assets();
